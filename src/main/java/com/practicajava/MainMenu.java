    /** Muestra el menú numerado agrupado por temas. */
    private static void mostrarMenu() {
        System.out.println("\n==================================================");
        System.out.println("     EJERCICIOS 25 - PRÁCTICA JAVA (Menú principal)");
        System.out.println("==================================================");
        for (int i = 0; i < TITULOS.length; i++) {
            if (i % 5 == 0) {
                System.out.println("-- " + TEMAS[i / 5] + " --");
            }
            System.out.printf("  %2d. %s%n", i + 1, TITULOS[i]);
        }
        System.out.println("   0. Salir");
    }

    public static void main(String[] args) {
        // Permite lanzar un ejercicio directamente: java ... MainMenu 7
        if (args.length > 0) {
            try {
                if (!ejecutarEjercicio(Integer.parseInt(args[0]))) {
                    System.out.println("Número de ejercicio no válido (1-25).");
                }
            } catch (NumberFormatException e) {
                System.out.println("Argumento no válido: " + args[0]);
            }
            return;
        }
        int opcion;
        do {
            mostrarMenu();
            opcion = Entrada.leerEntero("Elige un ejercicio (0-25): ");
            if (opcion == 0) {
                System.out.println("¡Hasta luego!");
            } else if (ejecutarEjercicio(opcion)) {
                System.out.println("\n>>> Ejercicio " + opcion + " finalizado. Volviendo al menú principal.");
            } else {
                System.out.println("Opción no válida. Introduce un número entre 0 y 25.");
            }
        } while (opcion != 0);
    }
